-- Brža noć (studeni 2026.): potez završava kad uloga odigra, mafija ima drugi krug,
-- a glumljeni potez mrtve uloge traje kao nedavni stvarni potez iste vrste.

-- početak trenutnog poteza (javni rok se računa iz njega; phase_ends_at je stvarni kraj)
ALTER TABLE game_state ADD COLUMN IF NOT EXISTS turn_started_at timestamptz;
-- glumi li se trenutni potez (uloga je mrtva)
ALTER TABLE game_state ADD COLUMN IF NOT EXISTS turn_fake boolean;
-- drugi krug mafije: kandidati iz prvog kruga ("12,15") i rok
ALTER TABLE game_state ADD COLUMN IF NOT EXISTS mafia_runoff_player_ids text;
ALTER TABLE game_state ADD COLUMN IF NOT EXISTS mafia_runoff_ends_at timestamptz;
-- meta mafije ove noći; nije strani ključ, kao ni ostali id-evi igrača u game_state
ALTER TABLE game_state ADD COLUMN IF NOT EXISTS night_mafia_target_id bigint;

-- Trajanja stvarnih noćnih poteza (od kraja naracije do kraja poteza), po vrsti poteza, iz svih soba.
-- Backend čuva zadnjih 500 po vrsti poteza.
CREATE TABLE IF NOT EXISTS turn_duration (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- MAFIA, DAMA, Doktor, Policajac ili Novinar
    turn        varchar(16) NOT NULL,
    duration_ms bigint      NOT NULL,
    created_at  timestamptz NOT NULL
);

CREATE INDEX IF NOT EXISTS turn_duration_turn_id_idx ON turn_duration (turn, id DESC);

ALTER TABLE turn_duration ENABLE ROW LEVEL SECURITY;
