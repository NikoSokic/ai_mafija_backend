-- Početna shema: tablice kakve su bile prije prve migracije, prema stanju u Supabaseu (studeni 2026.).
-- Na postojećoj bazi ne radi ništa, a na praznoj zajedno s ostalim migracijama izgradi cijelu bazu.

CREATE TABLE IF NOT EXISTS role (
    id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL,
    opis varchar(255)
);

CREATE TABLE IF NOT EXISTS lobby (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code           varchar(255) NOT NULL,
    status         varchar(255),
    max_players    integer,
    created_at     timestamptz DEFAULT now(),
    started_at     timestamptz DEFAULT now(),
    ended_at       timestamptz DEFAULT now(),
    host_player_id bigint
);

CREATE TABLE IF NOT EXISTS player (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nickname     varchar(255) NOT NULL,
    is_host      boolean DEFAULT false,
    is_alive     boolean DEFAULT true,
    joined_at    timestamptz DEFAULT now(),
    lobby_id     bigint REFERENCES lobby (id),
    role_id      bigint REFERENCES role (id),
    player_token varchar(255)
);

-- lobby i player pokazuju jedna na drugu, pa ova veza može tek kad postoje obje tablice
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'lobby_host_player_id_fkey') THEN
        ALTER TABLE lobby ADD CONSTRAINT lobby_host_player_id_fkey
            FOREIGN KEY (host_player_id) REFERENCES player (id);
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS lobby_role (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lobby_id   bigint NOT NULL REFERENCES lobby (id),
    role_id    bigint REFERENCES role (id),
    role_count bigint
);

CREATE TABLE IF NOT EXISTS game_state (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phase                   varchar(255) NOT NULL,
    round_number            integer DEFAULT 1,
    updated_at              timestamptz DEFAULT now(),
    lobby_id                bigint REFERENCES lobby (id),
    tie_break_player_ids    varchar(255),
    current_turn_role       varchar(255),
    night_killed_player_ids varchar(255)
);

CREATE TABLE IF NOT EXISTS game_action (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action_type             varchar(255) NOT NULL,
    phase                   varchar(255),
    round_number            integer,
    created_at              timestamptz DEFAULT now(),
    lobby_id                bigint REFERENCES lobby (id),
    player_id               bigint REFERENCES player (id),
    target_player_id        bigint REFERENCES player (id),
    second_target_player_id bigint CONSTRAINT fk_game_action_second_target_player REFERENCES player (id)
);

CREATE TABLE IF NOT EXISTS vote (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    round_number     integer NOT NULL,
    created_at       timestamptz,
    lobby_id         bigint REFERENCES lobby (id),
    voter_player_id  bigint REFERENCES player (id),
    target_player_id bigint REFERENCES player (id),
    phase            varchar(255) DEFAULT 'DAY'
);

